#!/usr/bin/env python3
"""Comics Now! - Safe Backup & Story Arc Metadata Stripping CLI

Safely extracts and archives original ComicInfo.xml files into a timestamped
backup directory with a full JSON manifest, then strips false-positive StoryArc
and StoryArcNumber tags from both archives/sidecars and comics-now.db.
"""
import os
import sys
import json
import sqlite3
import shutil
import zipfile
import re
from datetime import datetime, timezone
from pathlib import Path
import xml.etree.ElementTree as ET

# Add tagger module to path
REPO_ROOT = Path("/opt/comics-now")
sys.path.insert(0, str(REPO_ROOT / "tagger"))

from tagger_app.core.comicinfo import (
    _read_comic_info_source,
    sidecar_path_for,
    write_comic_info,
)

CN_DB_PATH = REPO_ROOT / "comics-now.db"
BACKUP_BASE = REPO_ROOT / "data" / "backups"


def is_generated_series_group(group_val: str) -> bool:
    """Return True if SeriesGroup was generated by event batch tagger."""
    if not group_val:
        return False
    g = group_val.strip().lower()
    return bool(
        re.search(r"\b(?:events|comic events|reading order)\b", g)
        or g.endswith(" events")
        or g == "dc comics events"
        or g == "marvel comics events"
    )


def strip_xml_story_arcs(xml_bytes: bytes) -> tuple[bytes, dict]:
    """Parse XML, remove StoryArc and StoryArcNumber, conditionally prune SeriesGroup, return (clean_bytes, removed_dict)."""
    root = ET.fromstring(xml_bytes)
    removed = {}

    sa = root.find("StoryArc")
    if sa is not None:
        removed["StoryArc"] = sa.text
        root.remove(sa)

    san = root.find("StoryArcNumber")
    if san is not None:
        removed["StoryArcNumber"] = san.text
        root.remove(san)

    sg = root.find("SeriesGroup")
    if sg is not None and is_generated_series_group(sg.text or ""):
        removed["SeriesGroup"] = sg.text
        root.remove(sg)

    clean_xml = ET.tostring(root, encoding="utf-8", xml_declaration=True)
    return clean_xml, removed


def main(dry_run: bool = False):
    print(f"[*] Starting Story Arc Backup & Stripping Job (dry_run={dry_run})...")
    if not CN_DB_PATH.exists():
        print(f"[-] Database not found at {CN_DB_PATH}")
        sys.exit(1)

    timestamp = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S")
    backup_dir = BACKUP_BASE / f"comicinfo-pre-strip-{timestamp}"

    conn = sqlite3.connect(str(CN_DB_PATH), timeout=15.0)
    conn.row_factory = sqlite3.Row
    cursor = conn.cursor()

    cursor.execute(
        "SELECT id, name, series, publisher, path, metadata FROM comics "
        "WHERE metadata LIKE '%StoryArc%' OR metadata LIKE '%SeriesGroup%'"
    )
    rows = [dict(r) for r in cursor.fetchall()]
    print(f"[*] Found {len(rows)} candidate comics in database with StoryArc/SeriesGroup metadata.")

    if not dry_run:
        backup_dir.mkdir(parents=True, exist_ok=True)
        print(f"[+] Created backup directory: {backup_dir}")

    manifest = {
        "timestamp": timestamp,
        "backupDirectory": str(backup_dir),
        "totalComics": len(rows),
        "comics": [],
    }

    backed_up_count = 0
    stripped_count = 0
    errors_count = 0

    for idx, c in enumerate(rows, start=1):
        cid = c["id"]
        cpath = c.get("path")
        cname = c.get("name")
        meta_raw = c.get("metadata") or "{}"
        try:
            db_meta = json.loads(meta_raw) if isinstance(meta_raw, str) else meta_raw
        except Exception:
            db_meta = {}

        xml_source = None
        has_sidecar = False

        if cpath and os.path.exists(cpath):
            sidecar = sidecar_path_for(cpath)
            has_sidecar = os.path.exists(sidecar)
            xml_source = _read_comic_info_source(cpath)

        backup_file_name = f"{cid}.ComicInfo.xml"
        backup_file_path = backup_dir / backup_file_name

        if xml_source and not dry_run:
            with open(backup_file_path, "wb") as bf:
                if isinstance(xml_source, str):
                    bf.write(xml_source.encode("utf-8"))
                else:
                    bf.write(xml_source)
            backed_up_count += 1

        manifest_entry = {
            "id": cid,
            "name": cname,
            "path": cpath,
            "hasSidecar": has_sidecar,
            "backupFile": str(backup_file_path) if xml_source else None,
            "originalDbMetadata": {
                "StoryArc": db_meta.get("StoryArc"),
                "StoryArcNumber": db_meta.get("StoryArcNumber"),
                "SeriesGroup": db_meta.get("SeriesGroup"),
            },
        }

        # Perform stripping
        if not dry_run:
            try:
                # 1. Update on-disk XML
                if xml_source and cpath and os.path.exists(cpath):
                    raw_bytes = xml_source.encode("utf-8") if isinstance(xml_source, str) else xml_source
                    clean_xml, removed = strip_xml_story_arcs(raw_bytes)
                    manifest_entry["removedXmlTags"] = removed

                    storage_mode = "sidecar" if has_sidecar or not zipfile.is_zipfile(cpath) else "archive"
                    write_comic_info(cpath, clean_xml.decode("utf-8", errors="replace"), storage_mode=storage_mode)

                # 2. Update DB metadata
                new_db_meta = dict(db_meta)
                db_removed = {}
                if "StoryArc" in new_db_meta:
                    db_removed["StoryArc"] = new_db_meta.pop("StoryArc")
                if "StoryArcNumber" in new_db_meta:
                    db_removed["StoryArcNumber"] = new_db_meta.pop("StoryArcNumber")
                if "SeriesGroup" in new_db_meta and is_generated_series_group(new_db_meta.get("SeriesGroup") or ""):
                    db_removed["SeriesGroup"] = new_db_meta.pop("SeriesGroup")

                manifest_entry["removedDbKeys"] = db_removed

                cursor.execute(
                    "UPDATE comics SET metadata = ?, updatedAt = datetime('now') WHERE id = ?",
                    (json.dumps(new_db_meta), cid),
                )
                stripped_count += 1
            except Exception as err:
                print(f"[-] Error processing {cname} ({cid}): {err}")
                errors_count += 1
                manifest_entry["error"] = str(err)

        manifest["comics"].append(manifest_entry)

    if not dry_run:
        conn.commit()
        conn.close()

        # Write manifest JSON
        manifest_path = backup_dir / "manifest.json"
        with open(manifest_path, "w", encoding="utf-8") as mf:
            json.dump(manifest, mf, indent=2)

        print("\n=======================================================")
        print(f"[+] Backup & Stripping Complete!")
        print(f"[+] Backup Directory: {backup_dir}")
        print(f"[+] Total Comics Processed: {len(rows)}")
        print(f"[+] XML Files Backed Up: {backed_up_count}")
        print(f"[+] Comics Stripped Clean: {stripped_count}")
        print(f"[+] Errors Encountered: {errors_count}")
        print(f"[+] Manifest Saved: {manifest_path}")
        print("=======================================================\n")
    else:
        conn.close()
        print(f"[*] Dry run finished. {len(rows)} comics would be processed.")


if __name__ == "__main__":
    dry = "--dry-run" in sys.argv
    main(dry_run=dry)
